#!/usr/bin/env python3
"""Write EXPERIMENT_TRACKER.md: one row per protocol grid with its run count, how many runs
finished (have final.json with every epoch logged), and an explicit DONE / INCOMPLETE status.
Status is derived from the exported results, never typed by hand. From repository root::

    PYTHONPATH=. .venv/bin/python -m scripts.make_tracker
"""

from __future__ import annotations

import csv
import json
from collections import Counter
from pathlib import Path

ROOT = Path("results/protocol_v2")


def _finished(run: Path) -> bool:
    fin, meta, metrics = run / "final.json", run / "meta.json", run / "metrics.csv"
    if not (fin.exists() and meta.exists() and metrics.exists()):
        return False
    epochs = int(json.loads(meta.read_text())["epochs"])
    rows = list(csv.DictReader(metrics.open()))
    return len(rows) == epochs and int(rows[-1]["epoch"]) == epochs


def main():
    lines = ["# Experiment Tracker", "",
             "Generated by `scripts/make_tracker.py` from `results/protocol_v2/`; do not edit by hand.",
             "A run counts as finished when it has `final.json`, `meta.json` and a `metrics.csv` with every epoch.", "",
             "| Grid | Runs | Finished | Datasets | Training sizes | Heads | Seeds | Status |",
             "|---|---|---|---|---|---|---|---|"]
    for grid in sorted(p for p in ROOT.iterdir() if p.is_dir()):
        runs = sorted(p for p in grid.iterdir() if p.is_dir())
        done = [r for r in runs if _finished(r)]
        metas = [json.loads((r / "meta.json").read_text()) for r in done]
        ds = Counter(m["dataset"] for m in metas)
        sizes = sorted({int(m["train_subset_size"]) for m in metas})
        heads = sorted({m["head"] for m in metas})
        seeds = sorted({int(m["seed"]) for m in metas})
        status = "DONE" if runs and len(done) == len(runs) else "INCOMPLETE"
        lines.append(f"| {grid.name} | {len(runs)} | {len(done)} | {', '.join(ds)} | {', '.join(map(str, sizes))} | "
                     f"{', '.join(heads)} | {', '.join(map(str, seeds))} | {status} |")
    Path("EXPERIMENT_TRACKER.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[5:]))


if __name__ == "__main__":
    main()
